// ⚠️ Alargado para `string`: o modo PEDIDO troca alguns rótulos pelos de pedido, e o tipo
// literal do `as const` não aceitaria a troca.
type Pt = (typeof T)["pt"];
export type Textos = { [K in keyof Pt]: Pt[K] extends string ? string : Pt[K] };
export const textos = (idioma: Idioma): Textos => T[idioma] as Textos;

const RESTRICAO: Record<Idioma, Record<string, string>> = {
  pt: { VEGANO: "Vegano", SEM_GLUTEN: "Sem glúten", SEM_LACTOSE: "Sem lactose" },
  en: { VEGANO: "Vegan", SEM_GLUTEN: "Gluten-free", SEM_LACTOSE: "Lactose-free" },
  de: { VEGANO: "Vegan", SEM_GLUTEN: "Glutenfrei", SEM_LACTOSE: "Laktosefrei" },
};
export const nomeRestricao = (idioma: Idioma, chave: string) => RESTRICAO[idioma][chave] ?? chave;

export const moeda = (v: number) =>
  v.toLocaleString("pt-BR", { style: "currency", currency: "BRL" });

export function idiomaDoNavegador(): Idioma {
  const l = (typeof navigator !== "undefined" ? navigator.language : "pt").slice(0, 2).toLowerCase();
  return l === "en" ? "en" : l === "de" ? "de" : "pt";
}
